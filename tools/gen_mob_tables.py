#!/usr/bin/env python3
"""lib/game/src/mob_tables.rs from rAthena's Renewal mob db.

What the pad's target lock needs and the client cannot learn from the server: which monsters attack from afar.
Kept: every monster whose `AttackRange` is RANGED_CELLS or more (archers, Mandragoras, Dimiks...); 2 and 3 are
mostly melee monsters with a long reach. Read from the server the client plays against, so the two agree.

Usage: tools/gen_mob_tables.py <rathena dir> [output file]   (output defaults to lib/game/src/mob_tables.rs)
"""

import sys
from pathlib import Path

import yaml

if len(sys.argv) < 2:
    sys.exit(__doc__)
RATHENA = Path(sys.argv[1])
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "lib/game/src/mob_tables.rs"
RANGED_CELLS = 4
PER_LINE = 8


def main():
    loader = getattr(yaml, "CSafeLoader", yaml.SafeLoader)
    mobs = {}
    for path in (RATHENA / "db/re/mob_db.yml", RATHENA / "db/import/mob_db.yml"):
        if path.exists():
            for mob in yaml.load(path.open(), Loader=loader).get("Body") or []:
                mobs[mob["Id"]] = mob.get("AttackRange", mobs.get(mob["Id"], 0))
    ranged = sorted((i, r) for i, r in mobs.items() if r >= RANGED_CELLS)
    cells = [f"({i}, {r})," for i, r in ranged]
    lines = [
        "// Generated by tools/gen_mob_tables.py from rAthena's db/re/mob_db.yml; do not edit.",
        "",
        f"/// (monster class, attack range in cells) for every monster that attacks from {RANGED_CELLS} cells or more",
        f"static RANGED: [(u16, u8); {len(ranged)}] = [",
    ]
    lines += ["    " + " ".join(cells[i : i + PER_LINE]) for i in range(0, len(cells), PER_LINE)]
    lines += [
        "];",
        "",
        f"/// The attack range of a monster that attacks from afar ({RANGED_CELLS} cells or more), `None` for the rest",
        "pub fn ranged_attack_range(class: u16) -> Option<u8> {",
        "    RANGED.binary_search_by_key(&class, |&(id, _)| id).ok().map(|i| RANGED[i].1)",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"{OUT}: {len(ranged)} ranged monsters of {len(mobs)}")


if __name__ == "__main__":
    main()
